const keyed: Record<SupportedLanguage, Dictionary> = { ENGLISH: en, HINDI: hi, GREEK: el, HAUSA: ha, GERMAN: de };

const normalize = (value: string) => value.replace(/\s+/g, " ").trim();
const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const interpolate = (template: string, values: Record<string, string>) => Object.entries(values).reduce((current, [key, value]) => current.replace(new RegExp(`{{${key}}}`, "g"), value), template);

const buildTemplateMatch = (template: string, value: string) => {
  const names: string[] = [];
  let pattern = "";
  let lastIndex = 0;
  const matcher = /{{(\w+)}}/g;
  let match: RegExpExecArray | null;

  while ((match = matcher.exec(template))) {
    pattern += escapeRegExp(template.slice(lastIndex, match.index));
    pattern += "(.+?)";
    names.push(match[1]);
    lastIndex = match.index + match[0].length;
  }

  pattern += escapeRegExp(template.slice(lastIndex));
  const result = new RegExp(`^${pattern}$`).exec(value);
  if (!result) return null;

  return names.reduce<Record<string, string>>((values, name, index) => { values[name] = result[index + 1]; return values; }, {});
};

const reverseKey = new Map<string, string>();
Object.entries(en).forEach(([key, value]) => reverseKey.set(normalize(value), key));

export const translateDisplayText = (language: SupportedLanguage, rawValue: string) => {
  if (language === "ENGLISH" || !rawValue || !rawValue.trim()) return rawValue;

  const leading = rawValue.match(/^\s*/)?.[0] || "";
  const trailing = rawValue.match(/\s*$/)?.[0] || "";
  const value = normalize(rawValue);

  const directKey = reverseKey.get(value);
  if (directKey) return `${leading}${keyed[language][directKey] || value}${trailing}`;

  const direct = additional[language][value];
  if (direct) return `${leading}${direct}${trailing}`;

  for (const [key, englishTemplate] of Object.entries(en)) {
    if (!englishTemplate.includes("{{")) continue;
    const values = buildTemplateMatch(normalize(englishTemplate), value);
    if (!values) continue;
    const translatedTemplate = keyed[language][key] || englishTemplate;
    return `${leading}${interpolate(translatedTemplate, values)}${trailing}`;
  }

  for (const [englishTemplate, translatedTemplate] of Object.entries(additional[language])) {
    if (!englishTemplate.includes("{{")) continue;
    const values = buildTemplateMatch(englishTemplate, value);
    if (!values) continue;
    return `${leading}${interpolate(translatedTemplate, values)}${trailing}`;
  }

  return rawValue;
};
